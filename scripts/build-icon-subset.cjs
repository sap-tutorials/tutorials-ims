// scripts/build-icon-subset.cjs
//
// Regenerate the subsetted fundamental-styles icon CSS (issue #1779).
//
// The upstream fundamental-styles icon.css (~80 KiB) defines ~800 glyph classes
// across three icon fonts (SAP-icons, SAP-icons-TNT, BusinessSuiteInAppSymbols).
// Our site uses `<ui5-icon>` web components for most glyphs and only a handful
// of `sap-icon--<glyph>` CSS classes. Shipping the full set render-blocking on
// every page is the "unused CSS" Lighthouse finding (#1779).
//
// This script emits hugo/assets/css/fundamental-styles-icon.css containing ONLY:
//   - the structural `[class*=sap-icon]` base rules (verbatim),
//   - all size/color/background modifier rules (verbatim, tiny),
//   - the glyph rules for the classes actually used in the source tree
//     (as reported by scripts/lib/used-sap-icons.cjs).
// The TNT and BusinessSuite fonts are dropped entirely (zero usage).
//
// Run manually after a `fundamental-styles` dep bump OR after adding/removing a
// `sap-icon--` class in the source:  `npm run build:icon-subset`
// test/icon-subset-guard.test.js fails CI if the committed subset ever falls
// behind the source (a used glyph not present in the subset).

'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { scanUsedGlyphs } = require('./lib/used-sap-icons.cjs');

const REPO_ROOT = path.join(__dirname, '..');
const UPSTREAM = path.join(REPO_ROOT, 'node_modules/fundamental-styles/dist/icon.css');
const OUT = path.join(REPO_ROOT, 'hugo/assets/css/fundamental-styles-icon.css');

/**
 * Parse the upstream icon.css into rule buckets.
 * Returns { header, baseRules[], modifierRules[], glyphRules:Map<name,rule> }.
 */
function parseUpstream(css) {
  const hm = css.match(/^\s*(\/\*![\s\S]*?\*\/)/);
  const header = hm ? hm[1] : '';
  const body = header ? css.slice(css.indexOf(header) + header.length) : css;

  const baseRules = [];
  const modifierRules = [];
  const glyphRules = new Map();

  // Crude but robust rule splitter: SELECTOR{DECLS} with no nested braces
  // (icon.css has none). Keep the exact source bytes for each kept rule.
  const ruleRe = /([^{}]+)\{([^{}]*)\}/g;
  let m;
  while ((m = ruleRe.exec(body)) !== null) {
    const sel = m[1].trim();
    const decls = m[2].trim();
    const rule = `${sel}{${decls}}`;

    // Single-glyph SAP-icons rule: `.sap-icon--NAME:before{content:"..."}`
    const g = sel.match(/^\.sap-icon--([a-z0-9-]+):before$/);
    if (g && /^content:/.test(decls)) {
      glyphRules.set(g[1], rule);
      continue;
    }
    // Structural base rules: `[class*=sap-icon]...` with NO specific `--NAME`
    // and NOT a TNT / BusinessSuite selector.
    if (
      sel.includes('[class*=sap-icon]') &&
      !sel.includes('sap-icon-TNT') &&
      !sel.includes('sap-icon-businessSuite')
    ) {
      const rest = sel.replace(/\[class\*=sap-icon\]/g, '');
      const modMatch = rest.match(/\.sap-icon--(sm|md|lg|xl|xxl|color-[a-z-]+|background-[a-z-]+)\b/);
      if (modMatch) {
        modifierRules.push(rule);
      } else if (!rest.includes('sap-icon--')) {
        baseRules.push(rule);
      }
      // else: a specific glyph modifier we don't recognise — skip (none exist)
    }
    // Everything else (TNT / BusinessSuite fonts + their glyphs) is dropped.
  }
  return { header, baseRules, modifierRules, glyphRules };
}

function main() {
  if (!fs.existsSync(UPSTREAM)) {
    console.error(`[icon-subset] upstream not found: ${UPSTREAM}\n` +
      `Run \`npm install\` so fundamental-styles is present.`);
    process.exit(1);
  }
  const upstreamCss = fs.readFileSync(UPSTREAM, 'utf8');
  const { header, baseRules, modifierRules, glyphRules } = parseUpstream(upstreamCss);

  const { glyphs: used, byFile } = scanUsedGlyphs(REPO_ROOT);

  const kept = [];
  const missing = [];
  for (const name of used) {
    if (glyphRules.has(name)) kept.push(name);
    else missing.push(name);
  }
  kept.sort();

  // Provenance header (keep the upstream copyright + note this is a subset).
  const version = (header.match(/Fundamental Library Styles v([\d.]+)/) || [])[1] || 'unknown';
  const banner =
    `/*! Fundamental Library Styles icon.css — SUBSET (v${version})\n` +
    ` * Copyright (c) SAP SE or an SAP affiliate company. Apache-2.0.\n` +
    ` * GENERATED by scripts/build-icon-subset.cjs — do not edit by hand.\n` +
    ` * Contains only the ${kept.length} sap-icon-- glyph classes used in source\n` +
    ` * (+ base + modifier rules). Regenerate: npm run build:icon-subset\n` +
    ` * Used glyphs: ${kept.join(', ')}\n` +
    ` */\n`;

  const out = banner +
    baseRules.join('\n') + '\n' +
    modifierRules.join('\n') + '\n' +
    kept.map((n) => glyphRules.get(n)).join('\n') + '\n';

  fs.writeFileSync(OUT, out, 'utf8');

  const upstreamBytes = Buffer.byteLength(upstreamCss);
  const outBytes = Buffer.byteLength(out);
  console.log(`[icon-subset] wrote ${path.relative(REPO_ROOT, OUT)}`);
  console.log(`[icon-subset] base=${baseRules.length} modifiers=${modifierRules.length} glyphs=${kept.length}/${glyphRules.size}`);
  console.log(`[icon-subset] size ${upstreamBytes} -> ${outBytes} bytes (-${Math.round((1 - outBytes / upstreamBytes) * 100)}%)`);
  if (missing.length) {
    console.warn(`[icon-subset] WARNING: ${missing.length} used class(es) have NO upstream glyph ` +
      `(render as blank today, pre-existing): ${missing.join(', ')}`);
    for (const name of missing) {
      const files = Object.entries(byFile).filter(([, gs]) => gs.includes(name)).map(([f]) => f);
      console.warn(`    - ${name}: ${files.join(', ')}`);
    }
  }
}

main();
