// scripts/apply-ui5-version.cjs
//
// Single-source-of-truth applicator for the SAPUI5 version used by the Admin UI
// and display-app. Reads app/admin-shell/ui5-version.json and propagates it to
// every derived consumer:
//
//   1. CDN bootstrap URLs  — app/admin-shell/webapp/index.html and
//      app/display-app/index.html are GENERATED from their *.template.html
//      siblings by substituting {{UI5_CDN_VERSION}} with `cdnVersion`.
//   2. ui5.yaml            — framework.version in every app/admin/*/ui5.yaml and
//      app/admin-shell/ui5.yaml is set to `cdnVersion` (ui5 build resolves this,
//      so it MUST be a live CDN patch).
//   3. minUI5Version floor — app/admin-shell/webapp/manifest.template.json's
//      minUI5Version is set to `minVersionFloor`. (The 50+ app/admin/*/manifest
//      floors are left to their own files — they are a compile floor, not a
//      loader URL, and do not break at runtime when a patch is purged.)
//
// WHY: the UI5 version was hardcoded in ~85 places. On 2026-10, SAP purged
// 1.136.0 from the CDN and the admin-shell bootstrap 404'd, taking the entire
// Admin UI down in PROD (PR #2658). This makes the bootstrap URL + build version
// derive from ONE file so a future bump is a one-line edit, and CI (via the
// `check-ui5-version` guard = this script with --check) fails any drift.
//
// Usage:
//   node scripts/apply-ui5-version.cjs            # write/update generated files
//   node scripts/apply-ui5-version.cjs --check    # exit 1 if any file is stale
//
// --check is the CI guard: it computes what every generated file SHOULD contain
// and diffs against disk without writing. --fix (alias for no flag) rewrites.

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');
const APP = path.join(REPO_ROOT, 'app');
const VERSION_FILE = path.join(APP, 'admin-shell', 'ui5-version.json');

const TOKEN = '{{UI5_CDN_VERSION}}';

/** Parse ui5-version.json, validating the two version fields look like semver. */
function readConfig() {
  let cfg;
  try {
    cfg = JSON.parse(fs.readFileSync(VERSION_FILE, 'utf8'));
  } catch (err) {
    throw new Error(`[apply-ui5-version] cannot read/parse ${rel(VERSION_FILE)}: ${err.message}`);
  }
  const semver = /^\d+\.\d+\.\d+$/;
  for (const key of ['cdnVersion', 'minVersionFloor']) {
    if (typeof cfg[key] !== 'string' || !semver.test(cfg[key])) {
      throw new Error(
        `[apply-ui5-version] ${rel(VERSION_FILE)} field "${key}" must be a semver like "1.148.12", got ${JSON.stringify(cfg[key])}`
      );
    }
  }
  return cfg;
}

function rel(p) {
  return path.relative(REPO_ROOT, p).replace(/\\/g, '/');
}

/**
 * Discover the files each consumer edits. Returns a list of {file, expected}
 * where `expected` is the full desired content on disk.
 *
 * ui5.yaml files are discovered dynamically (any new app/admin/<name>/ui5.yaml
 * is automatically in scope — no edit to this script needed when an admin app
 * is added), mirroring discover-admin-components.js.
 */
function computeTargets(cfg) {
  const targets = [];

  // 1. Generated index.html from templates.
  for (const tpl of [
    path.join(APP, 'admin-shell', 'webapp', 'index.template.html'),
    path.join(APP, 'display-app', 'index.template.html'),
  ]) {
    const out = tpl.replace(/index\.template\.html$/, 'index.html');
    const template = fs.readFileSync(tpl, 'utf8');
    if (!template.includes(TOKEN)) {
      throw new Error(`[apply-ui5-version] template ${rel(tpl)} is missing the ${TOKEN} token`);
    }
    // Strip the TEMPLATE banner comment from the generated output and mark it generated.
    const body = template.replaceAll(TOKEN, cfg.cdnVersion);
    targets.push({ file: out, expected: stampGenerated(body) });
  }

  // 2. ui5.yaml framework.version — discovered across admin + admin-shell.
  const ui5Yamls = discoverUi5Yamls();
  for (const file of ui5Yamls) {
    const src = fs.readFileSync(file, 'utf8');
    const expected = src.replace(
      /^(\s*version:\s*)["']?\d+\.\d+\.\d+["']?\s*$/m,
      `$1"${cfg.cdnVersion}"`
    );
    targets.push({ file, expected });
  }

  // 3. admin-shell manifest.template.json minUI5Version floor.
  const manifestTpl = path.join(APP, 'admin-shell', 'webapp', 'manifest.template.json');
  if (fs.existsSync(manifestTpl)) {
    const src = fs.readFileSync(manifestTpl, 'utf8');
    const expected = src.replace(
      /("minUI5Version":\s*)"\d+\.\d+\.\d+"/,
      `$1"${cfg.minVersionFloor}"`
    );
    targets.push({ file: manifestTpl, expected });
  }

  return targets;
}

/** Prepend a "generated — do not edit" banner right after the doctype. */
function stampGenerated(html) {
  const banner =
    '<!-- GENERATED by scripts/apply-ui5-version.cjs from index.template.html + ' +
    'app/admin-shell/ui5-version.json. DO NOT EDIT. Run `npm run apply:ui5-version`. -->';
  return html.replace(/(<!DOCTYPE html>\n)(<!--[\s\S]*?-->\n)?/, `$1${banner}\n`);
}

/** Find every app/admin/<name>/ui5.yaml plus app/admin-shell/ui5.yaml. */
function discoverUi5Yamls() {
  const found = [];
  const shell = path.join(APP, 'admin-shell', 'ui5.yaml');
  if (fs.existsSync(shell)) found.push(shell);
  const adminDir = path.join(APP, 'admin');
  for (const name of fs.readdirSync(adminDir)) {
    const y = path.join(adminDir, name, 'ui5.yaml');
    if (fs.existsSync(y)) found.push(y);
  }
  return found.sort();
}

// ── CLI ──────────────────────────────────────────────────────────────────────
function main() {
  const check = process.argv.includes('--check');
  const cfg = readConfig();
  const targets = computeTargets(cfg);

  const stale = [];
  for (const { file, expected } of targets) {
    const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
    if (actual === expected) continue;
    if (check) {
      stale.push(file);
    } else {
      fs.writeFileSync(file, expected);
    }
  }

  if (check) {
    if (stale.length > 0) {
      console.error(
        `[check-ui5-version] FAIL: ${stale.length} file(s) drifted from ${rel(VERSION_FILE)} ` +
        `(cdnVersion=${cfg.cdnVersion}, minVersionFloor=${cfg.minVersionFloor}):`
      );
      for (const f of stale) console.error(`  - ${rel(f)}`);
      console.error('\nFix with: npm run apply:ui5-version');
      process.exit(1);
    }
    console.log(`[check-ui5-version] OK — all ${targets.length} UI5-version consumers match ${rel(VERSION_FILE)}`);
    process.exit(0);
  }

  console.log(`[apply-ui5-version] applied cdnVersion=${cfg.cdnVersion} to ${targets.length} file(s).`);
}

if (require.main === module) main();

module.exports = { readConfig, computeTargets, discoverUi5Yamls };
