// Subset the vendored OpenDyslexic web fonts to the prose glyphs tutorials
// actually use (#1979), shrinking each WOFF2 from ~115 KB (full charset) to
// ~30 KB. Run manually after vendoring/updating the font:
//
//   node scripts/subset-opendyslexic.mjs
//
// Re-vendoring flow: drop the fresh FULL OpenDyslexic-{Regular,Bold}.woff2 into
// hugo/static/fonts/, then run this script — it subsets in place, verifies the
// result still covers every REQUIRED range against the actual font cmap (fails
// loudly otherwise), and rewrites the coverage manifest the CI guard checks.
//
// Requires Python fontTools (`python -m fontTools.subset`). Not wired into the
// build — the subsetted WOFF2 + manifest are committed artifacts.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, statSync, renameSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { REQUIRED_RANGES, UNICODES_ARG } from './opendyslexic-unicodes.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const fontsDir = path.join(root, 'hugo/static/fonts');
const WEIGHTS = ['OpenDyslexic-Regular.woff2', 'OpenDyslexic-Bold.woff2'];

// Resolve a working Python that can import fontTools.
function findPython() {
  for (const cmd of ['python', 'python3']) {
    const r = spawnSync(cmd, ['-c', 'import fontTools'], { encoding: 'utf8' });
    if (r.status === 0) return cmd;
  }
  console.error('ERROR: no Python with fontTools found (pip install fonttools brotli).');
  process.exit(1);
}
const PY = findPython();

// Expand REQUIRED_RANGES ("U+0020-007E" / "U+2013") into an explicit codepoint set.
function expandRequired() {
  const set = new Set();
  for (const { unicodes } of REQUIRED_RANGES) {
    const m = unicodes.replace(/U\+/g, '').split('-');
    const lo = parseInt(m[0], 16);
    const hi = m[1] !== undefined ? parseInt(m[1], 16) : lo;
    for (let cp = lo; cp <= hi; cp++) set.add(cp);
  }
  return set;
}

// Read the cmap codepoints of a font via fontTools.
function cmapCodepoints(file) {
  const code = `from fontTools.ttLib import TTFont;` +
    `f=TTFont(r"${file}");` +
    `print(",".join(str(cp) for t in f["cmap"].tables for cp in t.cmap.keys()))`;
  const r = spawnSync(PY, ['-c', code], { encoding: 'utf8' });
  if (r.status !== 0) { console.error(r.stderr); process.exit(1); }
  return new Set(r.stdout.trim().split(',').filter(Boolean).map(Number));
}

const manifestFiles = {};
for (const file of WEIGHTS) {
  const src = path.join(fontsDir, file);
  const tmp = `${src}.subset.tmp`;
  const before = statSync(src).size;
  // Capture what the ORIGINAL font actually contains within our required ranges.
  // OpenDyslexic doesn't ship every Latin Extended-A glyph (e.g. Ĉ Ĝ Ĥ Ĵ Ŭ), so
  // the invariant is "subsetting must not DROP a required glyph the font HAD" —
  // never "the font must contain every codepoint we listed".
  const req = expandRequired();
  const origHave = cmapCodepoints(src);
  const expected = [...req].filter((cp) => origHave.has(cp));

  const r = spawnSync(PY, [
    '-m', 'fontTools.subset', src,
    `--unicodes=${UNICODES_ARG}`,
    '--layout-features=*',
    '--flavor=woff2',
    `--output-file=${tmp}`,
  ], { encoding: 'utf8' });
  if (r.status !== 0) { console.error(r.stderr); process.exit(1); }

  // Verify the subset retained every required codepoint the original font had.
  const have = cmapCodepoints(tmp);
  const missing = expected.filter((cp) => !have.has(cp));
  if (missing.length) {
    console.error(`ERROR: ${file} subset DROPPED ${missing.length} required codepoints the font had, e.g. ` +
      missing.slice(0, 10).map((cp) => 'U+' + cp.toString(16).toUpperCase().padStart(4, '0')).join(', '));
    process.exit(1);
  }

  renameSync(tmp, src);
  const after = statSync(src).size;
  manifestFiles[file] = after;
  console.log(`${file}: ${before} -> ${after} bytes (${Math.round((1 - after / before) * 100)}% smaller)`);
}

const manifest = {
  note: 'OpenDyslexic subset coverage — generated by scripts/subset-opendyslexic.mjs (#1979). Do not hand-edit.',
  unicodes: REQUIRED_RANGES.map((r) => r.unicodes),
  files: manifestFiles,
};
const manifestPath = path.join(fontsDir, 'opendyslexic.subset.json');
writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
console.log(`wrote ${path.relative(root, manifestPath)}`);
