/**
 * Canonical question-type discriminators. Source of truth for the
 * `ValidationQuestion.type` union — import these instead of writing the
 * string literals so a future schema drift (`'free-text'`, `'long-text'`)
 * surfaces at the type-check level rather than as silently-broken
 * anti-leak filters.
 *
 * Test fixtures intentionally use the literals as inputs and don't
 * import these constants.
 */
export const QUESTION_TYPE_TEXT = 'text' as const
export const QUESTION_TYPE_MCQ = 'multiple-choice' as const
export type QuestionType = typeof QUESTION_TYPE_TEXT | typeof QUESTION_TYPE_MCQ

export interface ValidationQuestion {
  id: string
  question: string
  type: 'multiple-choice' | 'text'
  options?: string[]
  // [#1740] Choice cardinality for MCQ questions. Mirrors the legacy AEM
  // distinction between `###Rule single-choice` (radio, exactly one correct)
  // and `###Rule multiple-choice` (checkbox, one-or-more correct). Absent for
  // `text` questions and treated as 'single' by consumers when undefined
  // (backward compat with questions emitted before this field existed).
  choiceMode?: 'single' | 'multiple'
  // CHANGED: correctAnswer is now optional. Omitted for AI-graded
  // questions (issue #209) — the reference answer ships server-side
  // via ValidateAnswerSpecs and never enters the public Hugo
  // frontmatter or <script id="tutorial-data"> JSON.
  // Also omitted for multiple-choice questions (choiceMode === 'multiple'),
  // which carry their reference set in `correctAnswers` instead (#1740).
  // The hugo-apps consumer (`hugo-apps/src/validation/grading.ts`) defines its own local
  // interface that keeps correctAnswer: string required; AI-graded questions are routed
  // away from gradeAnswers() at the call site (Task 10).
  correctAnswer?: string
  // [#1740] The full set of correct options for a multi-select
  // (choiceMode === 'multiple') question. Grading is exact set match —
  // every entry here must be selected and nothing else. Populated only for
  // non-AI multiple-choice; single-choice/text use `correctAnswer`.
  correctAnswers?: string[]
  // NEW — opted in via ###Grading: ai-judged OR via regex rule types (issue #209).
  aiGrading?: boolean
  // [#208] Set true when this question was generated by the AI quiz
  // generator. Joins to the eval harness; ships in public frontmatter
  // for MCQ + sidecar for text. Indistinguishable from hand-authored
  // questions to the validation widget.
  aiAuthored?: boolean
  /**
   * [#208] Build-time sentinel set by the AI quiz generator (`srv/lib/ai-quiz-generator.js`)
   * for AI-authored text questions. Carries the reference answer through
   * the cache + eval harness; ALWAYS stripped before public Hugo
   * frontmatter emission (`materializeForPipeline` in
   * `scripts/lib/expand-ai-authored.ts` moves it to `correctAnswer` for
   * the pipeline shape, and the bridge strip in `scripts/fetch-tutorials.ts`
   * deletes `correctAnswer` again before frontmatter emit).
   *
   * Should NEVER appear in:
   *  - Hugo frontmatter / `<script id="tutorial-data">` JSON
   *  - Network responses
   *  - Logs
   *
   * Only legitimate readers: `materializeForPipeline`, the eval CSV emitter
   * (`scripts/evaluate-ai-quizzes.ts`), and the cache JSON file at
   * `.tutorial-cache/<slug>.ai-quiz-cache.json`.
   */
  __aiCorrectAnswer?: string
}

